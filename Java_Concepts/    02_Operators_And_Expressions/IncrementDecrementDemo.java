public class IncrementDecrementDemo
{
    public static void main(String[] args)
    {
        int a = 10;
        int b = 10;

        System.out.println("Pre Increment  : " + (++a));
        System.out.println("Post Increment : " + (b++));
        System.out.println("Final A        : " + a);
        System.out.println("Final B        : " + b);
    }
}