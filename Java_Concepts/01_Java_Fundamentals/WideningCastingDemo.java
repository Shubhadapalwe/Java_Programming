/*
 * Program Name : WideningCastingDemo.java
 * Concept      : Implicit Type Casting
 */

public class WideningCastingDemo
{
    public static void main(String[] args)
    {
        int iValue = 100;

        double dValue = iValue;

        System.out.println("Integer Value : " + iValue);
        System.out.println("Double Value  : " + dValue);
    }
}